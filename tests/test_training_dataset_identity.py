import shutil

import pytest

from policy_doctor.artifacts import InputError
from policy_doctor.training_dataset_identity import fingerprint_training_dataset


def snapshot(tmp_path):
    root = tmp_path / 'original'
    root.mkdir()
    (root / 'meta').mkdir()
    (root / 'meta/info.json').write_text('{"kind":"test"}')
    (root / 'data.parquet').write_bytes(b'explicit generated bytes, not a native parquet fixture')
    return root


def test_identity_survives_move_and_detects_changed_input(tmp_path):
    original = snapshot(tmp_path)
    first = fingerprint_training_dataset(original)
    copy = tmp_path / 'moved'
    shutil.copytree(original, copy)
    assert fingerprint_training_dataset(copy) == first
    (copy / 'data.parquet').write_bytes(b'changed')
    assert fingerprint_training_dataset(copy)['dataset_id'] != first['dataset_id']


def test_added_file_changes_identity_and_is_not_silently_excluded(tmp_path):
    root = snapshot(tmp_path)
    before = fingerprint_training_dataset(root)
    (root / '.extra').write_text('included')
    after = fingerprint_training_dataset(root)
    assert before['dataset_id'] != after['dataset_id']
    assert '.extra' in {record['path'] for record in after['files']}


@pytest.mark.parametrize('special', ['symlink', 'fifo'])
def test_special_files_refused_without_reading(tmp_path, special):
    import os

    root = snapshot(tmp_path)
    if special == 'symlink':
        (root / 'link').symlink_to(root / 'data.parquet')
    else:
        os.mkfifo(root / 'pipe')
    with pytest.raises(InputError, match='symlinks and special files'):
        fingerprint_training_dataset(root)


def test_explicit_byte_and_file_bounds_refuse_partial_identity(tmp_path):
    root = snapshot(tmp_path)
    for bound in ({'max_files': 1}, {'max_bytes': 1}):
        with pytest.raises(InputError, match='exceeds max_files/max_bytes'):
            fingerprint_training_dataset(root, **bound)


@pytest.mark.parametrize('bound', [{'max_files': True}, {'max_files': 0}, {'max_bytes': False}, {'max_bytes': 17 * 1024**3}])
def test_invalid_bounds_refused(tmp_path, bound):
    with pytest.raises(InputError, match='max_files'):
        fingerprint_training_dataset(tmp_path, **bound)


def test_missing_and_empty_snapshots_refused(tmp_path):
    with pytest.raises(InputError, match='existing regular'):
        fingerprint_training_dataset(tmp_path / 'absent')
    with pytest.raises(InputError, match='no materialized files'):
        fingerprint_training_dataset(tmp_path)
