def test_window_audit_unchanged_without_video_features(tmp_path):
    root = dataset(tmp_path, [(3, 0, 0.0)], {0: 3}, with_data=True)
    info = json.loads((root / "meta" / "info.json").read_text())
    info["features"].pop(KEY)
