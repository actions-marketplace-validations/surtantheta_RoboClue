"""Video index detectors: declared video features against episode columns, files and MP4 header frame counts.

Fixtures reproduce the patterns found on public data: lerobot/berkeley_autolab_ur5 (28 episodes whose interval
runs past their video file, with the clip at the next file's start) and SO-101-robot-learning/so101_pick_place
(a declared camera with no episode columns or files). Generated bytes only.
"""
import io
import json
import struct

import pyarrow as pa
import pyarrow.parquet as pq
import pytest

from policy_doctor import hub
from policy_doctor.artifacts import InputError
from policy_doctor.video_index import HEADER_INDEX, _LocalMedia, check_video_index, header_timing
from policy_doctor.windows import audit_episode_windows

KEY = "observation.images.front"


def box(kind, payload):
    return struct.pack(">I4s", len(payload) + 8, kind) + payload


def full(payload=b"", flags=0):
    return struct.pack(">I", flags) + payload


def movie(frames):
    """Single-track AV1 MP4 with ``frames`` samples at 5 fps (timescale 10240, 2048 ticks per sample)."""
    payloads = [bytes([i % 251]) * (8 + i % 3) for i in range(frames)]
    ftyp = box(b"ftyp", b"isom\0\0\0\0isomav01")
    mdat = box(b"mdat", b"".join(payloads))
    mvhd = bytearray(100)
    struct.pack_into(">II", mvhd, 12, 1000, frames * 200)
    mdhd = bytearray(24)
    struct.pack_into(">II", mdhd, 12, 10240, frames * 2048)
    visual = bytearray(78)
    struct.pack_into(">H", visual, 6, 1)
    struct.pack_into(">HH", visual, 24, 640, 480)
    sample = box(b"av01", bytes(visual) + box(b"av1C", b"\x81\0\0\0"))
    stsd = box(b"stsd", full(struct.pack(">I", 1) + sample))
    stsz = box(b"stsz", full(struct.pack(">II", 0, frames) + struct.pack(">" + "I" * frames, *map(len, payloads))))
    stts = box(b"stts", full(struct.pack(">III", 1, frames, 2048)))
    stsc = box(b"stsc", full(struct.pack(">IIII", 1, 1, frames, 1)))
    stco = box(b"stco", full(struct.pack(">II", 1, len(ftyp) + 8)))
    stss = box(b"stss", full(struct.pack(">II", 1, 1)))
    stbl = box(b"stbl", stsd + stsz + stts + stsc + stco + stss)
    dinf = box(b"dinf", box(b"dref", full(struct.pack(">I", 1) + box(b"url ", full(flags=1)))))
    hdlr = box(b"hdlr", full(struct.pack(">I", 0) + b"vide" + b"\0" * 12))
    mdia = box(b"mdia", box(b"mdhd", bytes(mdhd)) + hdlr + box(b"minf", dinf + stbl))
    return ftyp + mdat + box(b"moov", box(b"mvhd", bytes(mvhd)) + box(b"trak", mdia))


def dataset(tmp_path, episodes, files, *, extra_keys=(), write_videos=True, with_data=False):
    """episodes: list of (length, file_index, from_s); files: {file_index: frames}."""
    root = tmp_path / "dataset"
    (root / "meta" / "episodes" / "chunk-000").mkdir(parents=True)
    features = {KEY: {"dtype": "video", "shape": [480, 640, 3]}, "action": {"dtype": "float32", "shape": [2]}}
    features.update({k: {"dtype": "video", "shape": [480, 640, 3]} for k in extra_keys})
    total = sum(length for length, _, _ in episodes)
    (root / "meta" / "info.json").write_text(json.dumps({
        "codebase_version": "v3.0", "fps": 5, "total_frames": total, "total_episodes": len(episodes),
        "data_path": "data/chunk-{chunk_index:03d}/file-{file_index:03d}.parquet",
        "video_path": "videos/{video_key}/chunk-{chunk_index:03d}/file-{file_index:03d}.mp4", "features": features}))
    rows, start = [], 0
    for ep, (length, file_index, begin) in enumerate(episodes):
        rows.append({"episode_index": ep, "length": length, "dataset_from_index": start, "dataset_to_index": start + length,
                     "data/chunk_index": 0, "data/file_index": 0, f"videos/{KEY}/chunk_index": 0,
                     f"videos/{KEY}/file_index": file_index, f"videos/{KEY}/from_timestamp": begin,
                     f"videos/{KEY}/to_timestamp": begin + length / 5})
        start += length
    pq.write_table(pa.Table.from_pylist(rows), root / "meta" / "episodes" / "chunk-000" / "file-000.parquet")
    if with_data:
        (root / "data" / "chunk-000").mkdir(parents=True)
        data, index = [], 0
        for ep, (length, _, _) in enumerate(episodes):
            for frame in range(length):
                data.append({"index": index, "episode_index": ep, "frame_index": frame, "action": [0.0, 0.0]})
                index += 1
        pq.write_table(pa.Table.from_pylist(data), root / "data" / "chunk-000" / "file-000.parquet")
    if write_videos:
        for file_index, frames in files.items():
            path = root / "videos" / KEY / "chunk-000" / f"file-{file_index:03d}.mp4"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(movie(frames))
    return root


def codes(findings):
    return {f["code"] for f in findings}


def test_header_timing_reads_frame_count_from_headers_only(tmp_path):
    path = tmp_path / "v.mp4"
    path.write_bytes(movie(7))
    media = _LocalMedia(path)
    timing = header_timing(media)
    media.close()
    assert timing["status"] == "parsed" and timing["sample_count"] == 7
    assert timing["last_sample_start_s"] == pytest.approx(1.2) and timing["end_s"] == pytest.approx(1.4)


def test_healthy_intervals_pass(tmp_path):
    root = dataset(tmp_path, [(3, 0, 0.0), (2, 0, 0.6)], {0: 5})
    findings, coverage = check_video_index(root)
    assert findings == [] and coverage["video_index"] == "checked 1 video file(s)"


def test_berkeley_pattern_interval_past_end_with_next_file_hint(tmp_path):
    # Episode 1 is declared in file-000 at 0.6 s, but file-000 holds only episode 0's 3 frames; file-001 starts with
    # an unreferenced 0.4 s span (episode 1's 2 frames) before episode 2.
    root = dataset(tmp_path, [(3, 0, 0.0), (2, 0, 0.6), (3, 1, 0.4)], {0: 3, 1: 5})
    findings, _ = check_video_index(root)
    past = next(f for f in findings if f["code"] == "video.interval_past_end")
    assert past["status"] == "error" and [e["episode_index"] for e in past["episodes"]] == [1]
    assert past["episodes"][0]["next_file_starts_with_unreferenced_span_of_this_length"] is True
    assert "video_utils.py:262-265" in past["message"] and "recover-video-reference" in past["message"]


def test_overrun_without_matching_next_file_has_no_hint(tmp_path):
    root = dataset(tmp_path, [(3, 0, 0.0), (2, 0, 0.6)], {0: 3})
    past = next(f for f in check_video_index(root)[0] if f["code"] == "video.interval_past_end")
    assert past["episodes"][0]["next_file_starts_with_unreferenced_span_of_this_length"] is False
    assert "recover-video-reference" not in past["message"]


